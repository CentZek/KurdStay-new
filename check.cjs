const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('dist/app.js','utf8');
const context={localStorage:{getItem:()=>null},Set,document:{querySelector:()=>({addEventListener(){}})}};
vm.createContext(context);
for(const file of ['listings-data.js','listing-media.js','media.js','creator.js'])vm.runInContext(fs.readFileSync('dist/'+file,'utf8'),context);
vm.runInContext(source.slice(0,source.indexOf("$('#aboutBtn').onclick=about;")),context);
const run=s=>vm.runInContext(s,context),records=JSON.parse(fs.readFileSync('dist/listings.json','utf8')).listings;
const duhok=records.filter(p=>p.region==='Duhok'),mapped=run('listings.filter(p=>mapPosition(p)).length');
assert.equal(run('getFiltered().length'),duhok.length);
for(const type of ['Land','House','Apartment'])assert.equal(run('state.type='+JSON.stringify(type)+';getFiltered().length'),duhok.filter(p=>p.type===type).length);
assert.equal(run("state.type='All';state.district='Semel';getFiltered().length"),duhok.filter(p=>p.district==='Semel').length);
assert.equal(run("state.district='All';state.query='zakho';getFiltered()[0].district"),'Zakho');
assert.equal(run("state.query='';state.sort='low';getFiltered()[0].price"),Math.min(...duhok.map(p=>p.price)));
assert.equal(run("state.sort='high';getFiltered()[0].price"),Math.max(...duhok.map(p=>p.price)));
assert.equal(run("state.savedOnly=true;saved.add(75186);getFiltered()[0].id"),75186);
assert.equal(run("state.savedOnly=false;state.inView=true;map={getBounds:()=>({contains:()=>true})};getFiltered().length"),run("regionInventory('Duhok').filter(p=>mapPosition(p)).length"));
assert.equal(run("map={getBounds:()=>({contains:()=>false})};getFiltered().length"),0);
assert.ok(run("listings.every(p=>p.location.status==='source-reported'&&p.location.accuracyMeters===null&&p.location.parcelGeometry===null&&p.location.verifiedAt===null)"));
assert.match(run("locationDetails(listings.find(p=>p.type==='Land'))"),/No parcel boundary or parcel number/);
assert.match(run("locationDetails(listings.find(p=>p.type==='Apartment'))"),/Apartment unit/);
assert.equal(run('listings.some(hasVerifiedLocation)'),false);
assert.equal(run("hasVerifiedLocation({...listings[0],lat:36.8,lng:43,location:{status:'source-reported'}})"),false);
assert.equal(run("hasVerifiedLocation({...listings[0],lat:null,lng:null,location:{status:'verified'}})"),false);
assert.equal(run('groupMapListings(listings).flatMap(g=>g.items).length'),mapped);
assert.equal(run('new Set(groupMapListings(listings).flatMap(g=>g.items.map(p=>p.id))).size'),mapped);
assert.equal(run('groupMapListings(listings,p=>({x:0,y:0})).length'),1);
assert.equal(run('groupMapListings(listings,p=>({x:p[0]*1000000,y:p[1]*1000000})).flatMap(g=>g.items).length'),mapped);
assert.equal(run("mapPosition({...listings[0],location:{sourceLat:null,sourceLng:null}})"),null);
assert.equal(run("mapPosition({...listings[0],location:{sourceLat:999,sourceLng:43}})"),null);
assert.equal(run("JSON.stringify(mapPosition({...listings[0],lat:36,lng:43,location:{status:'verified'}}))"),'[36,43]');
assert.deepEqual(JSON.parse(run('JSON.stringify(listings)')),records);
for(const key of ['id','url','reference'])assert.equal(new Set(records.map(p=>key==='id'?p.id:p.source[key])).size,records.length);
for(const p of records){
 assert.ok(['Duhok','Erbil','Sulaymaniyah','Halabja'].includes(p.region));assert.equal(p.currency,'USD');assert.equal(p.priceBasis,'TOTAL');assert.ok(Number.isFinite(p.price)&&p.price>0&&p.area>0);
 assert.match(p.source.url,/^https:\/\/paya-realestate\.com\/en\/properties\/[^/]+$/);assert.equal(p.source.catalogStatus,'Active');
 assert.equal(p.source.checkedDate,'2026-11-01');assert.match(p.source.postedDate,/^\d{4}-\d{2}-\d{2}$/);
 assert.equal(p.lat,null);assert.equal(p.lng,null);assert.equal(p.img,null);
 for(const key of ['beds','baths'])assert.ok(p[key]===null||Number.isInteger(p[key])&&p[key]>=0);
}
assert.equal(run("escapeHTML('<script>\"&')"),'&lt;script&gt;&quot;&amp;');
console.log('PASS: '+records.length+' distinct priced source ads; filters, source identity, location evidence, grouping completeness, schema and escaping');
